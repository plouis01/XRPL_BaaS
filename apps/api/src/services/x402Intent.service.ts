// x402 intent + route registry service. SPRINT_10_PLAN.md §4.2.
//
// Two surfaces:
//
//   1. createIntent / findIntent / consumeIntent — used by the x402
//      middleware on the request hot path. consumeIntent is the
//      atomic claim-once gate that prevents two concurrent retries
//      from double-spending the same Payment tx (HIGH-08 precedent
//      in apps/worker/src/jobs/txSubmitter.ts).
//
//   2. listRoutes / createRoute / deleteRoute — dashboard CRUD for
//      a client's registry of gated paths. The middleware looks up
//      `(clientId, pathPattern)` to decide what to quote on a 402.
//
// All amounts are stored as text (matches every other XRPL amount
// column in the schema; BigInt comparisons happen at the verifier).
// Destination tags are derived deterministically from the intent ID
// via @railforge/xrpl-core's intentIdToDestinationTag — the verifier
// re-derives and compares against the on-ledger tx field.
//
// IMPORTANT: this service does NOT touch rippled. It only manages DB
// state. Verification (which fetches the tx + meta) lives in
// x402Verify.service.ts.

import { and, db, eq, isNull, schema, sql } from '@railforge/db';
import {
  type X402AssetKind,
  intentIdToDestinationTag,
  newIntentId,
  parseX402Asset,
} from '@railforge/xrpl-core';
import { logger } from '../logger.ts';

const log = logger.child({ component: 'x402-intent' });

/** Intent lifetime in seconds. Matches the webhook replay window (5 min). */
export const X402_INTENT_TTL_SECONDS = 300;

// ── Public types ────────────────────────────────────────────────────────────

export interface X402Intent {
  id: string;
  clientId: string | null;
  resourcePath: string;
  payeeAddress: string;
  assetKind: X402AssetKind;
  /** MPTokenIssuanceID hex for `mpt`; null for `xrp`. */
  assetKey: string | null;
  /** Amount in smallest units (drops for XRP, raw MPT units otherwise). */
  amount: string;
  destinationTag: number;
  expiresAt: Date;
  consumedAt: Date | null;
  consumingTxHash: string | null;
  createdAt: Date;
}

export interface X402Route {
  id: string;
  clientId: string;
  pathPattern: string;
  payeeAddress: string;
  assetKind: X402AssetKind;
  assetKey: string | null;
  priceAmount: string;
  isActive: boolean;
  createdAt: Date;
}

export interface CreateIntentInput {
  resourcePath: string;
  payeeAddress: string;
  /** Asset reference: `XRP` or `mpt:<48-hex>`. Validated by xrpl-core. */
  asset: string;
  /** Amount as a positive decimal integer string. */
  amount: string;
  /** Mode A: the RailForge client whose route we matched. Null in Mode B. */
  clientId?: string | null;
}

export interface CreateRouteInput {
  clientId: string;
  pathPattern: string;
  payeeAddress: string;
  asset: string;
  amount: string;
}

// ── Helpers ─────────────────────────────────────────────────────────────────

function rowToIntent(row: typeof schema.x402Intents.$inferSelect): X402Intent {
  // assetKind is `text` in the DB but constrained to `'xrp' | 'mpt'` by the
  // create path. Narrow at the boundary so callers get the union type.
  const kind = row.assetKind;
  if (kind !== 'xrp' && kind !== 'mpt') {
    throw new Error(`x402Intent: invalid assetKind in DB row: ${kind}`);
  }
  return {
    id: row.id,
    clientId: row.clientId,
    resourcePath: row.resourcePath,
    payeeAddress: row.payeeAddress,
    assetKind: kind,
    assetKey: row.assetKey,
    amount: row.amount,
    destinationTag: row.destinationTag,
    expiresAt: row.expiresAt,
    consumedAt: row.consumedAt,
    consumingTxHash: row.consumingTxHash,
    createdAt: row.createdAt,
  };
}

function rowToRoute(row: typeof schema.x402Routes.$inferSelect): X402Route {
  const kind = row.assetKind;
  if (kind !== 'xrp' && kind !== 'mpt') {
    throw new Error(`x402Route: invalid assetKind in DB row: ${kind}`);
  }
  return {
    id: row.id,
    clientId: row.clientId,
    pathPattern: row.pathPattern,
    payeeAddress: row.payeeAddress,
    assetKind: kind,
    assetKey: row.assetKey,
    priceAmount: row.priceAmount,
    isActive: row.isActive,
    createdAt: row.createdAt,
  };
}

// ── Intent surface ──────────────────────────────────────────────────────────

/**
 * Mint a new intent. The middleware calls this on a request with no
 * `X-PAYMENT` header — the returned intent goes into the 402 body.
 *
 * The intent id is generated by xrpl-core's `newIntentId`; the destination
 * tag is derived deterministically by `intentIdToDestinationTag` so the
 * verifier can re-derive without an extra DB read.
 */
export async function createIntent(input: CreateIntentInput): Promise<X402Intent> {
  const asset = parseX402Asset(input.asset);
  const intentId = newIntentId();
  const destinationTag = intentIdToDestinationTag(intentId);
  const expiresAt = new Date(Date.now() + X402_INTENT_TTL_SECONDS * 1000);

  const [row] = await db
    .insert(schema.x402Intents)
    .values({
      id: intentId,
      clientId: input.clientId ?? null,
      resourcePath: input.resourcePath,
      payeeAddress: input.payeeAddress,
      assetKind: asset.kind,
      assetKey: asset.key,
      amount: input.amount,
      destinationTag,
      expiresAt,
    })
    .returning();

  if (!row) {
    throw new Error('x402: createIntent: insert returned no row');
  }
  log.debug(
    {
      intentId,
      resourcePath: input.resourcePath,
      asset: input.asset,
      destinationTag,
    },
    'x402 intent created',
  );
  return rowToIntent(row);
}

/**
 * Fetch an intent by id. Returns null if not found.
 *
 * Does NOT enforce expiry or consumption — callers (the verifier) want
 * to distinguish "no such id" from "expired" from "already consumed"
 * with discrete error codes.
 */
export async function findIntent(intentId: string): Promise<X402Intent | null> {
  const rows = await db
    .select()
    .from(schema.x402Intents)
    .where(eq(schema.x402Intents.id, intentId))
    .limit(1);
  const row = rows[0];
  return row ? rowToIntent(row) : null;
}

/**
 * Atomically claim an intent. Returns true if this call won the race and
 * the intent is now consumed by `txHash`; false if another caller beat us
 * to it OR the row no longer matches the unconsumed/unexpired predicate.
 *
 * Implementation note: a partial unique index on `consuming_tx_hash` (see
 * migration 0021) prevents a single tx hash from satisfying two distinct
 * intents — if the WHERE matches but a sibling intent already set
 * `consuming_tx_hash = txHash`, Postgres raises a unique-violation. We
 * surface that as `false` (not an error) because the caller's correct
 * action is identical: reject the retry and reissue a 402.
 */
export async function consumeIntent(intentId: string, txHash: string): Promise<boolean> {
  try {
    const result = await db
      .update(schema.x402Intents)
      .set({
        consumedAt: new Date(),
        consumingTxHash: txHash,
      })
      .where(
        and(
          eq(schema.x402Intents.id, intentId),
          isNull(schema.x402Intents.consumedAt),
          sql`${schema.x402Intents.expiresAt} > now()`,
        ),
      )
      .returning({ id: schema.x402Intents.id });
    return result.length > 0;
  } catch (err) {
    // 23505 = unique_violation on consuming_tx_hash. Means another intent
    // already burned this txHash — caller must treat it as "claim failed".
    const code = (err as { code?: string })?.code;
    if (code === '23505') {
      log.warn({ intentId, txHash }, 'x402 consume: tx already used by another intent');
      return false;
    }
    throw err;
  }
}

// ── Route surface ───────────────────────────────────────────────────────────

/**
 * Look up the registered x402 route for `(clientId, path)`. Returns null
 * if no matching active route exists.
 *
 * Path matching is exact this sprint — pattern globbing is deferred until
 * we see real usage signal a need for it. SPRINT_10_PLAN §10.
 */
export async function findRoute(clientId: string, path: string): Promise<X402Route | null> {
  const rows = await db
    .select()
    .from(schema.x402Routes)
    .where(
      and(
        eq(schema.x402Routes.clientId, clientId),
        eq(schema.x402Routes.pathPattern, path),
        eq(schema.x402Routes.isActive, true),
      ),
    )
    .limit(1);
  const row = rows[0];
  return row ? rowToRoute(row) : null;
}

export async function listRoutes(clientId: string): Promise<X402Route[]> {
  const rows = await db
    .select()
    .from(schema.x402Routes)
    .where(eq(schema.x402Routes.clientId, clientId));
  return rows.map(rowToRoute);
}

export async function createRoute(input: CreateRouteInput): Promise<X402Route> {
  const asset = parseX402Asset(input.asset);
  const [row] = await db
    .insert(schema.x402Routes)
    .values({
      clientId: input.clientId,
      pathPattern: input.pathPattern,
      payeeAddress: input.payeeAddress,
      assetKind: asset.kind,
      assetKey: asset.key,
      priceAmount: input.amount,
    })
    .returning();
  if (!row) {
    throw new Error('x402: createRoute: insert returned no row');
  }
  return rowToRoute(row);
}

/**
 * Soft-delete a route (sets is_active=false). Returns true on success,
 * false when no matching row was found (so dashboard can return 404 vs 204).
 * Soft-delete keeps the row visible for audit and preserves the unique
 * (client_id, path_pattern) constraint footprint should the client
 * recreate the same path later.
 */
export async function deleteRoute(clientId: string, routeId: string): Promise<boolean> {
  const result = await db
    .update(schema.x402Routes)
    .set({ isActive: false })
    .where(and(eq(schema.x402Routes.id, routeId), eq(schema.x402Routes.clientId, clientId)))
    .returning({ id: schema.x402Routes.id });
  return result.length > 0;
}
